// Generates all service keys for a fresh deployment. Writes .secrets/keys.env (gitignored).
// Usage: node scripts/gen-keys.mjs  (refuses to overwrite an existing file)
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { x25519 } from "@noble/curves/ed25519.js";
import { bytesToHex, randomBytes } from "@noble/hashes/utils.js";

const out = ".secrets/keys.env";
if (existsSync(out)) { console.error(`${out} exists; refusing to overwrite`); process.exit(1); }
mkdirSync(".secrets", { recursive: true });
const evm = (name) => { const pk = generatePrivateKey(); return [`${name}_PRIVATE_KEY=${pk}`, `${name}_ADDRESS=${privateKeyToAccount(pk).address}`]; };
const x = (name) => { const sk = randomBytes(32); return [`${name}_SECRET_KEY=${bytesToHex(sk)}`, `${name}_PUBLIC_KEY=${bytesToHex(x25519.getPublicKey(sk))}`]; };
const lines = [
  "# Generated by scripts/gen-keys.mjs — NEVER commit.",
  ...evm("VERIFIER"), ...evm("MIRROR"), ...evm("SEPOLIA_DEPLOYER"),
  ...x("ESCROW"), ...x("GATED"),
  `READER_TOKEN_SECRET=${bytesToHex(randomBytes(32))}`,
];
writeFileSync(out, lines.join("\n") + "\n", { mode: 0o600 });
console.log(lines.filter((l) => /ADDRESS|PUBLIC_KEY/.test(l)).join("\n"));
